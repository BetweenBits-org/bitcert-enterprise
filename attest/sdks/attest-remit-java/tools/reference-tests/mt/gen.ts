/**
 * Runs every input of cases.ts through the TypeScript SDK and writes what it
 * answers into the Java test Mt103ReferenceTest, hard-coded.
 *
 *   node tools/reference-tests/mt/gen.ts               write the test (and print a summary)
 *   node tools/reference-tests/mt/gen.ts --out <file>  write it somewhere else
 *   node tools/reference-tests/mt/gen.ts --summary     print the summary only
 */
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseSwiftMessages, SwiftMessageError } from '../../../../../packages/attest-remit/src/index.ts';
import cases from './cases.ts';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const outAt = process.argv.indexOf('--out');
const OUT = outAt > 0 ? path.resolve(process.argv[outAt + 1]!)
  : path.resolve(HERE, '../../../src/test/java/com/stonehash/attest/remit/swift/Mt103ReferenceTest.java');

/** One UTF-16 unit as it is written inside a Java string literal. */
function unit(c: number): string {
  if (c === 0x22) return '\\"';
  if (c === 0x5c) return '\\\\';
  if (c === 0x0a) return '\\n';
  if (c === 0x0d) return '\\r';
  if (c === 0x09) return '\\t';
  if (c >= 0x20 && c <= 0x7e) return String.fromCharCode(c);
  return `\\u${c.toString(16).padStart(4, '0')}`;
}

/** A Java string expression for s: literals of at most `width` source characters, joined with +, broken after line ends. */
function javaString(s: string, indent: string, width = 110): string {
  const pieces: string[] = [];
  let cur = '';
  for (let i = 0; i < s.length; i++) {
    const u = unit(s.charCodeAt(i));
    cur += u;
    if (u === '\\n' || cur.length >= width) {
      pieces.push(cur);
      cur = '';
    }
  }
  if (cur !== '' || pieces.length === 0) pieces.push(cur);
  return pieces.map((p) => `"${p}"`).join(`\n${indent}+ `);
}

interface Answer { payments?: unknown[]; error?: { code: string; field?: string; message: string } }

function answer(input: string): Answer {
  try {
    return { payments: JSON.parse(JSON.stringify(parseSwiftMessages(input))) };
  } catch (e) {
    if (!(e instanceof SwiftMessageError)) throw e;
    return { error: { code: e.code, ...(e.field !== undefined ? { field: e.field } : {}), message: e.message } };
  }
}

const rows: string[] = [];
const groups: string[] = [];
for (const c of cases) {
  const a = answer(c.input);
  if (!groups.includes(c.group)) groups.push(c.group);
  const shown = a.error
    ? `ERR ${a.error.code} [${a.error.field ?? ''}] ${a.error.message}`
    : `OK  ${a.payments!.length} × ${JSON.stringify(a.payments!.map((p) => {
      const { digest: _d, ...rest } = p as Record<string, unknown>;
      return rest;
    }))}`;
  console.log(`${c.group}/${c.name}: ${shown.slice(0, process.argv.includes('--long') ? 4000 : 400)}`);
  const ind = '                ';
  rows.push(`        {${javaString(c.group, ind)}, ${javaString(c.name, ind)}, ${javaString(c.note, ind)},\n`
    + `            ${javaString(c.input, '            ')},\n`
    + `            ${javaString(JSON.stringify(a), '            ', 120)}},`);
}

if (!process.argv.includes('--summary')) {
  const methods = groups.map((g) => {
    const name = g.charAt(0).toUpperCase() + g.slice(1);
    return `    static void test${name}() {\n        run("${g}");\n    }\n`;
  }).join('\n');
  const java = `package com.stonehash.attest.remit.swift;

import com.stonehash.attest.remit.Json;
import com.stonehash.attest.remit.RemitException;
import java.util.ArrayList;
import java.util.List;
import java.util.Map;

/**
 * What the TypeScript SDK answers for MT103 inputs the golden vectors do not
 * reach, hard-coded: the same payments (as its JSON has them) or the same
 * refusal, code, field and words.
 *
 * <p>Generated by {@code probe/gen.ts} from the inputs in {@code probe/cases.ts},
 * which runs each of them through the reference ({@code packages/attest-remit});
 * regenerate it rather than editing it.
 */
final class Mt103ReferenceTest {
    private Mt103ReferenceTest() {
    }

    /** Group, name, what the case shows, the input (a string), the reference's answer as JSON. */
    private static final String[][] CASES = {
${rows.join('\n')}
    };

${methods}
    static void testEveryCaseIsRun() {
        int n = 0;
        for (String g : new String[] {${groups.map((g) => `"${g}"`).join(', ')}}) {
            for (String[] c : CASES) {
                n += c[0].equals(g) ? 1 : 0;
            }
        }
        if (n != CASES.length || CASES.length != ${cases.length}) {
            throw new AssertionError("a case belongs to no group: " + n + " of " + CASES.length);
        }
    }

    private static void run(String group) {
        List<String> failures = new ArrayList<>();
        for (String[] c : CASES) {
            if (c[0].equals(group)) {
                String d = difference(c[3], Golden.map(Json.parse(c[4])));
                if (d != null) {
                    failures.add(c[1] + " (" + c[2] + "): " + d);
                }
            }
        }
        Golden.none(failures, group);
    }

    /** How this package's answer differs from the reference's, or null. */
    static String difference(String input, Map<String, Object> expected) {
        List<Object> got = new ArrayList<>();
        try {
            for (SwiftPayment p : Swift.parseAll(input)) {
                got.add(p.toJson());
            }
        } catch (RemitException e) {
            if (expected.get("error") == null) {
                return "refused, the reference reads it — " + e.code() + ": " + e.getMessage();
            }
            return Golden.difference(Golden.expectedError(expected.get("error")), Golden.errorOf(e));
        }
        if (expected.get("error") != null) {
            return "read, the reference refuses it — " + Json.compact(expected.get("error"));
        }
        return Golden.difference(expected.get("payments"), got);
    }
}
`;
  writeFileSync(OUT, java);
  console.log(`\nwrote ${cases.length} cases in ${groups.length} groups to ${OUT}`);
}
